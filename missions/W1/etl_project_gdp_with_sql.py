def extract(url: str, output_json: str) -> None:
    """
    Extract raw GDP table from Wikipedia and save as JSON.
    """
    log("EXTRACT START")

    headers = {"User-Agent": "Mozilla/5.0"}
    response = requests.get(url, headers=headers)
    response.raise_for_status()

    soup = BeautifulSoup(response.text, "html.parser")

    # Wikipedia GDP 테이블은 wikitable class 사용
    table = soup.find("table", class_="wikitable")
    rows = table.find("tbody").find_all("tr")

    records = []
    for row in rows:
        # th와 td를 함께 수집 (헤더/국가명 구조 차이 때문)
        cells = row.find_all(["th", "td"])
        records.append(
            [cell.get_text(strip=True) for cell in cells]
        )

    header = records[0]
    data = records[1:]

    # 행마다 컬럼 개수가 다른 경우를 대비해 길이 보정
    max_len = max(len(row) for row in records)

    def normalize(row):
        return row + [None] * (max_len - len(row))

    header = normalize(header)
    data = [normalize(row) for row in data]

    df = pd.DataFrame(data, columns=header)

    df.to_json(
        output_json,
        orient="records",
        force_ascii=False,
        indent=2
    )

    log("EXTRACT END")


