def transform(input_json: str, output_json: str) -> None:
    """
    Transform raw GDP data and save cleaned JSON.
    """
    log("TRANSFORM START")

    df_raw = pd.read_json(input_json)

    # Wikipedia 테이블 기준:
    # 0번째 컬럼: Country / 1번째 컬럼: IMF GDP
    df = df_raw.iloc[:, [0, 1]].copy()
    df.columns = ["Country", "IMF"]

    # 국가명에 포함된 각주([1], [a] 등) 제거
    df["Country"] = (
        df["Country"]
        .astype(str)
        .str.replace(r"\[.*?\]", "", regex=True)
        .str.strip()
    )

    # 숫자가 아닌 GDP 표현 제거
    df["IMF"] = (
        df["IMF"]
        .astype(str)
        .str.replace(",", "", regex=False)
        .replace(["—", "N/a", "—N/a"], pd.NA)
    )

    df["IMF"] = pd.to_numeric(df["IMF"], errors="coerce")
    df = df.dropna(subset=["IMF"])

    # IMF 데이터 단위: million USD -> billion USD 변환
    df["GDP_USD_billion"] = (df["IMF"] / 1000).round(2)

    # GDP 내림차순 정렬
    df = df.sort_values("GDP_USD_billion", ascending=False)

    df[["Country", "GDP_USD_billion"]].to_json(
        output_json,
        orient="records",
        force_ascii=False,
        indent=2
    )

    log("TRANSFORM END")


# ============================================================
# Load
# ============================================================

def load(transformed_json: str) -> None:
    """
    Load transformed GDP data into SQLite.
    """
    log("LOAD START")

    df = pd.read_json(transformed_json)

    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    cur.execute("""
        CREATE TABLE IF NOT EXISTS Countries_by_GDP (
            Country TEXT,
            GDP_USD_billion REAL
        )
    """)

    # 데이터만 갱신하고 테이블 구조는 유지
    cur.execute("DELETE FROM Countries_by_GDP")

    df.to_sql(
        "Countries_by_GDP",
        conn,
        if_exists="append",
        index=False
    )

    conn.commit()
    conn.close()

    log("LOAD END")


